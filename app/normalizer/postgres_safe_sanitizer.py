from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from app.model.document import Document


@dataclass(frozen=True, slots=True)
class SanitizationReport:
    changed_fields: int = 0
    removed_nul_count: int = 0
    replaced_surrogate_count: int = 0

    @property
    def changed(self) -> bool:
        return bool(self.changed_fields or self.removed_nul_count or self.replaced_surrogate_count)


class PostgresSafeSanitizer:
    """Sanitize strings at the PostgreSQL/JSON boundary without changing meaning.

    PostgreSQL text/jsonb cannot store U+0000. Some engineering PDFs generated by
    printer drivers (for example Adobe PSL for Canon) expose NUL bytes in PDF
    metadata even though page text is valid. Python's JSON encoder can serialize
    this as ``\\u0000`` but PostgreSQL rejects it when casting to jsonb.

    The sanitizer therefore removes only database-invalid NUL characters and
    replaces isolated UTF-16 surrogate code points with U+FFFD. It deliberately
    does *not* perform NFKC/case/whitespace normalization so Japanese/Chinese
    engineering text remains semantically unchanged.
    """

    @classmethod
    def sanitize_text(cls, value: str) -> tuple[str, int, int]:
        text = str(value)
        nul_count = text.count("\x00")
        if nul_count:
            text = text.replace("\x00", "")

        surrogate_count = sum(1 for ch in text if 0xD800 <= ord(ch) <= 0xDFFF)
        if surrogate_count:
            text = "".join(
                "\ufffd" if 0xD800 <= ord(ch) <= 0xDFFF else ch
                for ch in text
            )

        return text, nul_count, surrogate_count

    @classmethod
    def sanitize_value(cls, value: Any) -> tuple[Any, SanitizationReport]:
        changed_fields = 0
        nul_count = 0
        surrogate_count = 0

        if isinstance(value, str):
            cleaned, removed, replaced = cls.sanitize_text(value)
            if cleaned != value:
                changed_fields = 1
            return cleaned, SanitizationReport(changed_fields, removed, replaced)

        if isinstance(value, dict):
            cleaned_dict: dict[str, Any] = {}
            for raw_key, raw_value in value.items():
                key, key_report = cls.sanitize_value(str(raw_key))
                cleaned_value, value_report = cls.sanitize_value(raw_value)
                cleaned_dict[str(key)] = cleaned_value
                changed_fields += key_report.changed_fields + value_report.changed_fields
                nul_count += key_report.removed_nul_count + value_report.removed_nul_count
                surrogate_count += key_report.replaced_surrogate_count + value_report.replaced_surrogate_count
            return cleaned_dict, SanitizationReport(changed_fields, nul_count, surrogate_count)

        if isinstance(value, list):
            cleaned_list = []
            for item in value:
                cleaned_item, report = cls.sanitize_value(item)
                cleaned_list.append(cleaned_item)
                changed_fields += report.changed_fields
                nul_count += report.removed_nul_count
                surrogate_count += report.replaced_surrogate_count
            return cleaned_list, SanitizationReport(changed_fields, nul_count, surrogate_count)

        if isinstance(value, tuple):
            cleaned_items, report = cls.sanitize_value(list(value))
            return tuple(cleaned_items), report

        if isinstance(value, set):
            # JSONB cannot represent sets. Preserve deterministic content as a list.
            cleaned_items, report = cls.sanitize_value(sorted(value, key=lambda item: str(item)))
            return cleaned_items, report

        return value, SanitizationReport()

    @classmethod
    def sanitize_document(cls, document: Document) -> SanitizationReport:
        changed_fields = 0
        nul_count = 0
        surrogate_count = 0

        def merge(report: SanitizationReport) -> None:
            nonlocal changed_fields, nul_count, surrogate_count
            changed_fields += report.changed_fields
            nul_count += report.removed_nul_count
            surrogate_count += report.replaced_surrogate_count

        cleaned_name, report = cls.sanitize_value(document.file_name)
        document.file_name = str(cleaned_name)
        merge(report)

        cleaned_type, report = cls.sanitize_value(document.file_type)
        document.file_type = str(cleaned_type)
        merge(report)

        cleaned_metadata, report = cls.sanitize_value(dict(document.metadata or {}))
        document.metadata = dict(cleaned_metadata)
        merge(report)

        for page in document.pages:
            cleaned, report = cls.sanitize_value(page.text)
            page.text = str(cleaned)
            merge(report)

        for block in document.blocks:
            cleaned, report = cls.sanitize_value(block.text)
            block.text = str(cleaned)
            merge(report)
            if block.style_name is not None:
                cleaned, report = cls.sanitize_value(block.style_name)
                block.style_name = str(cleaned)
                merge(report)
            cleaned_cells, report = cls.sanitize_value(list(block.cells))
            block.cells = [str(cell) for cell in cleaned_cells]
            merge(report)
            cleaned_meta, report = cls.sanitize_value(dict(block.metadata or {}))
            block.metadata = dict(cleaned_meta)
            merge(report)

        for chapter in document.chapters:
            cleaned, report = cls.sanitize_value(chapter.id)
            chapter.id = str(cleaned)
            merge(report)
            if chapter.title_jp is not None:
                cleaned, report = cls.sanitize_value(chapter.title_jp)
                chapter.title_jp = str(cleaned)
                merge(report)
            if chapter.title_en is not None:
                cleaned, report = cls.sanitize_value(chapter.title_en)
                chapter.title_en = str(cleaned)
                merge(report)
            cleaned_meta, report = cls.sanitize_value(dict(chapter.metadata or {}))
            chapter.metadata = dict(cleaned_meta)
            merge(report)

        for section in document.sections:
            for attr in ("id", "chapter_id", "parent_section_id", "title_jp", "title_en"):
                current = getattr(section, attr, None)
                if current is None:
                    continue
                cleaned, report = cls.sanitize_value(current)
                setattr(section, attr, str(cleaned))
                merge(report)
            cleaned_meta, report = cls.sanitize_value(dict(section.metadata or {}))
            section.metadata = dict(cleaned_meta)
            merge(report)

        for content in document.contents:
            cleaned, report = cls.sanitize_value(content.text)
            content.text = str(cleaned)
            merge(report)
            for attr in ("chapter_id", "section_id"):
                current = getattr(content, attr, None)
                if current is None:
                    continue
                cleaned, report = cls.sanitize_value(current)
                setattr(content, attr, str(cleaned))
                merge(report)
            cleaned_meta, report = cls.sanitize_value(dict(content.metadata or {}))
            content.metadata = dict(cleaned_meta)
            merge(report)

        final_report = SanitizationReport(changed_fields, nul_count, surrogate_count)
        if final_report.changed:
            document.metadata["postgres_sanitizer_status"] = "SANITIZED"
            document.metadata["postgres_sanitized_field_count"] = final_report.changed_fields
            document.metadata["postgres_removed_nul_count"] = final_report.removed_nul_count
            document.metadata["postgres_replaced_surrogate_count"] = final_report.replaced_surrogate_count
            warnings = list(document.metadata.get("import_warning_codes") or [])
            if "POSTGRES_UNICODE_SANITIZED" not in warnings:
                warnings.append("POSTGRES_UNICODE_SANITIZED")
            document.metadata["import_warning_codes"] = warnings
            if document.metadata.get("import_status") in (None, "", "IMPORTED"):
                document.metadata["import_status"] = "IMPORTED_SANITIZED"
        else:
            document.metadata.setdefault("postgres_sanitizer_status", "CLEAN")

        return final_report
